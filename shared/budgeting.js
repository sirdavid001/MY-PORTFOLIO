const CURRENCY_BY_REGION = Object.fromEntries(
  Object.entries(REGIONS_BY_CURRENCY).flatMap(([currency, regions]) =>
    regions.split(" ").map((region) => [region, currency])
  )
);

export function getLocationFactor(countryCode) {
  const code = String(countryCode || "NG").toUpperCase();
  const key = CURRENCY_BY_REGION[code] === "EUR" ? "EU" : code;
  return LOCATION_FACTORS[key] ?? LOCATION_FACTORS.default;
}

export function getCurrencyForCountry(countryCode, fallbackCurrency = "NGN") {
  const code = String(countryCode || "NG").toUpperCase();
  return CURRENCY_BY_REGION[code] || fallbackCurrency;
}

export function formatMoney(amount, currency) {
  return new Intl.NumberFormat("en", {
    style: "currency",
    currency,
    maximumFractionDigits: 0,
  }).format(amount);
}
